def _load_settings() -> dict:
    try:
        return json.loads(SETTINGS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _save_settings(settings: dict) -> None:
    try:
        CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        SETTINGS_FILE.write_text(
            json.dumps(settings, ensure_ascii=False, indent=2), encoding="utf-8"
        )
    except OSError:
        pass


def detect_language() -> str:
    """Best-effort match of the system locale to a supported language."""
    name = ""
    try:
        name = locale.getlocale()[0] or ""
    except (ValueError, TypeError):
        name = ""
    name = name or os.environ.get("LANG", "")
    lowered = name.lower()
    if lowered.startswith("ru"):
        return "ru"
    if lowered.startswith("de"):
        return "de"
    if lowered.startswith("fr"):
        return "fr"
    if lowered.startswith("es"):
        return "es"
    if lowered.startswith("pt"):
        return "pt-BR"
    if lowered.startswith(("zh", "cmn")):
        return "zh-Hans"
    if lowered.startswith("en"):
        return "en"
    return DEFAULT_LANGUAGE


def load_language() -> str:
    code = _load_settings().get("language")
    if code in dict(LANGUAGES):
        return code
    return detect_language()


_current = load_language()


def set_language(code: str) -> str:
    global _current
    if code in dict(LANGUAGES):
        _current = code
        settings = _load_settings()
        settings["language"] = code
        _save_settings(settings)
    return _current


def get_language() -> str:
    return _current


def language_name(code: str | None = None) -> str:
    return dict(LANGUAGES).get(code or _current, code or _current)


def tr(key: str, **kwargs) -> str:
    """Translate ``key`` for the current language, formatting ``kwargs``."""
    text = TRANSLATIONS.get(_current, {}).get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text
